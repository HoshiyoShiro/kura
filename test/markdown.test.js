// Run: node test/markdown.test.js
const { md } = require('../public/markdown.js');
let fail = 0;
const t = (name, src, has, not) => {
  const h = md(src);
  const ok = (has || []).every(x => h.includes(x)) && (not || []).every(x => !h.includes(x));
  if (!ok) { fail++; console.log('FAIL', name, '\n  ', JSON.stringify(h)); } else console.log('ok  ', name);
};
t('heading levels', '# A\n###### F', ['<h2>A</h2>', '<h6>F</h6>']);
t('bold italic strike', '**b** *i* ~~s~~ ***bi*** __b2__ _i2_', ['<b>b</b>', '<i>i</i>', '<s>s</s>', '<b><i>bi</i></b>', '<b>b2</b>', '<i>i2</i>']);
t('snake_case untouched', 'use my_var_name here', ['my_var_name'], ['<i>']);
t('math stars untouched', '2 * 3 * 4', ['2 * 3 * 4'], ['<i>']);
t('inline code protects markup', 'run `a **b** <x>` now', ['<code>a **b** &lt;x&gt;</code>'], ['<b>']);
t('line breaks', 'one\ntwo', ['one<br>\ntwo']);
t('link', '[site](https://a.com/x?y=1&z=2)', ['<a href="https://a.com/x?y=1&amp;z=2" target="_blank" rel="noopener noreferrer">site</a>']);
t('bare url', 'see https://a.com/path.', ['>https://a.com/path</a>.']);
t('image becomes link', '![alt](https://a.com/i.png)', ['>alt</a>'], ['<img']);
t('xss javascript link', '[x](javascript:alert(1))', [], ['<a ']);
t('xss html', '<script>alert(1)</script> <img src=x onerror=alert(1)>', ['&lt;script&gt;', '&lt;img'], ['<script', '<img']);
t('xss attr breakout', '[x](https://a.com/"onmouseover="alert(1))', [], ['onmouseover="']);
t('xss in table', '| a |\n|---|\n| <b>x</b> |', ['&lt;b&gt;'], ['<b>x']);
t('escapes', String.raw`\*not italic\* and \# no`, ['*not italic*', '# no'], ['<i>']);
t('fenced code', '```js\nconst a = "<b>";\n```', ['<pre><code class="lang-js">const a = &quot;&lt;b&gt;&quot;;'], ['<b>']);
t('tilde fence', '~~~\nx\n~~~', ['<pre><code>x']);
t('unterminated fence', '```\nabc', ['<pre><code>abc']);
t('hr', 'a\n\n---\n\nb', ['<hr>']);
t('blockquote multi + nested', '> a\n> b\n>\n> - x', ['<blockquote>', '<ul><li>x</li></ul>']);
t('bullets', '- a\n- b', ['<ul><li>a</li>\n'.replace('\n',''), '<li>b</li></ul>']);
t('nested', '- a\n  - b\n    - c\n- d', ['<ul><li>a<ul><li>b<ul><li>c</li></ul></li></ul></li><li>d</li></ul>']);
t('ordered start', '3. x\n4. y', ['<ol start="3">']);
t('mixed nested', '1. a\n   - b\n2. c', ['<ol><li>a<ul><li>b</li></ul></li><li>c</li></ol>']);
t('loose list', '- a\n\n- b', ['<li>a</li><li>b</li>']);
t('tasks', '- [ ] todo\n- [x] done', ['<li class="task"><input type="checkbox" disabled> todo', 'disabled checked> done']);
t('table + align', '| A | B |\n|:--|--:|\n| 1 | 2 |', ['<th class="al-left">A</th>', '<th class="al-right">B</th>', '<td class="al-right">2</td>', 'class="tbl"']);
t('table no outer pipes', 'A | B\n--|--\n1 | 2', ['<th>A</th>', '<td>2</td>']);
t('list interrupts paragraph', 'intro\n- a', ['<p>intro</p>', '<ul><li>a</li></ul>']);
t('bold in list', '- **k**: v', ['<li><b>k</b>: v</li>']);
t('placeholder injection', 'x \u0001 0 \u0001', [], ['\u0001']);
t('empty', '', [], []);
console.log(fail ? fail + ' FAILED' : 'all passed'); process.exit(fail ? 1 : 0);
